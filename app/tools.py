import time
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from .db import uid
from .providers import fetch_public, search_web
from .security import SECRET, workspace_path


class Args(BaseModel):
    model_config = ConfigDict(extra="forbid")


class Query(Args):
    query: str = Field(min_length=1, max_length=2000)


class SupportDraft(Args):
    category: str = Field(min_length=1, max_length=100)
    draft: str = Field(min_length=1, max_length=2000)
    questions: list[str] = Field(max_length=8)
    reason: str = Field(min_length=1, max_length=500)
    assignee: str = Field(min_length=1, max_length=100)
    status: Literal["needs_details", "manual_review"]
    source_ids: list[str] = Field(max_length=10)


class Fetch(Args):
    url: str = Field(min_length=1, max_length=2000)


class Memory(Args):
    key: str = Field(min_length=1, max_length=100)
    value: str = Field(min_length=1, max_length=2000)
    expected_version: int | None = Field(default=None, ge=0)


class Code(Args):
    code: str = Field(min_length=1, max_length=30000)


class FileOp(Args):
    operation: Literal["ls", "read", "write", "glob", "grep"]
    path: str = Field(default="/workspace/", min_length=1, max_length=500)
    content: str = Field(default="", max_length=100000)
    pattern: str = Field(default="", max_length=200)
    offset: int = Field(default=0, ge=0)
    limit: int = Field(default=100, ge=1, le=200)


class EditFile(Args):
    path: str = Field(min_length=1, max_length=500)
    old_string: str = Field(min_length=1, max_length=20000)
    new_string: str = Field(max_length=20000)
    replace_all: bool = False


class Shell(Args):
    command: str = Field(min_length=1, max_length=5000)


class Export(Args):
    path: str = Field(min_length=1, max_length=500)


class Report(Args):
    filename: str = Field(default="report.md", max_length=150)
    content: str = Field(min_length=1, max_length=100000)


class Ticket(Args):
    title: str = Field(min_length=1, max_length=200)
    body: str = Field(min_length=1, max_length=5000)


class Tasks(Args):
    tasks: list[str] = Field(min_length=1, max_length=8)


class Delegate(Args):
    role: Literal["researcher", "analyst", "reviewer"]
    task: str = Field(min_length=1, max_length=5000)


class Dataset(Args):
    query_name: Literal["documents", "tickets", "usage"]


class DeepTask(Args):
    task: str = Field(min_length=1, max_length=5000)


class Empty(Args):
    pass


